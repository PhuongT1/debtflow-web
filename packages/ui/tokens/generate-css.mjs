import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import ts from 'typescript';
const directory = path.dirname(fileURLToPath(import.meta.url));
const nativeRequire = createRequire(import.meta.url);
function load(file) {
  const filename = path.resolve(directory, 'src', file);
  const output = ts.transpileModule(fs.readFileSync(filename, 'utf8'), {
    compilerOptions: { module: ts.ModuleKind.CommonJS },
  }).outputText;
  const module = { exports: {} };
  const require = (name) =>
    name.startsWith('.')
      ? load(
          path.relative(
            path.join(directory, 'src'),
            fs.existsSync(path.resolve(path.dirname(filename), name + '.ts'))
              ? path.resolve(path.dirname(filename), name + '.ts')
              : path.resolve(path.dirname(filename), name, 'index.ts'),
          ),
        )
      : nativeRequire(name);
  new Function('require', 'module', 'exports', output)(require, module, module.exports);
  return module.exports;
}
const { themeSchemes } = load('schemes/index.ts');
const { designTokens } = load('index.ts');
const kebab = (key) => key.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase());
const declarations = (scheme) =>
  Object.entries(scheme)
    .flatMap(([group, roles]) =>
      Object.entries(roles).map(([role, value]) => `  --df-${group}-${kebab(role)}: ${value};`),
    )
    .join('\n');
const result =
  '/* Generated by generate-css.mjs; edit palette/, schemes/, effects/ or base.css. */\n' +
  fs.readFileSync(path.join(directory, 'src/base.css'), 'utf8') +
  `\n:root {\n${Object.entries(designTokens.table.sizes)
    .flatMap(([size, values]) =>
      Object.entries(values).map(
        ([key, value]) => `  --df-table-${size}-${kebab(key)}: ${value}px;`,
      ),
    )
    .join('\n')}\n}\n` +
  `\n:root, :root.light {\n  color-scheme: light;\n${declarations(themeSchemes.light)}\n}\n` +
  `\n@media (prefers-color-scheme: dark) {\n  :root:not(.light):not(.dark) {\n    color-scheme: dark;\n${declarations(themeSchemes.dark)}\n  }\n}\n` +
  `\n:root.dark {\n  color-scheme: dark;\n${declarations(themeSchemes.dark)}\n}\n`;
const target = path.join(directory, 'src/tokens.css');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== result)
    throw new Error('Token CSS is stale; run npm run generate -w @packages/ui-tokens');
} else fs.writeFileSync(target, result);
